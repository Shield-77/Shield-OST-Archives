const char *tr(const char *french) {
    if (!english || !french) return french;
    for (unsigned i=0;i<sizeof(strings)/sizeof(strings[0]);++i)
        if (!strcmp(french,strings[i].fr)) return strings[i].en;
    if (!strncmp(french,"Acces refuse (",14)) return "Access denied: private or unavailable archive.";
    if (!strncmp(french,"Serveur HTTP ",13)) return "HTTP server error.";
    if (!strncmp(french,"Reseau : ",9)) return "Network error. Check Wi-Fi and retry.";
    return french;
}
